// Lucide 1.72.0, ISC. Sources and license live in studio/assets/lucide.
// Inline paths inherit the control's ink. File-backed SVG images do not.
import {readdir, readFile, writeFile} from 'node:fs/promises';
const base = new URL('../studio/assets/lucide/', import.meta.url);
function path(tag, a) {
  const n = key => Number(a[key] || 0);
  // A leading relative moveto can contain implicit relative lineto pairs.
  // Reset the origin before concatenation; changing m to M would distort them.
  if (tag === 'path') return /^m/.test(a.d) ? 'M0 0 '+a.d : a.d;
  if (tag === 'line') return `M${n('x1')} ${n('y1')}L${n('x2')} ${n('y2')}`;
  if (tag === 'polyline' || tag === 'polygon') return 'M' + a.points.trim().split(/[ ,]+/).map(Number).reduce((s,v,i)=>s+(i%2?' ':i?'L':'')+v,'') + (tag==='polygon'?'Z':'');
  if (tag === 'circle' || tag === 'ellipse') {
    const x=n('cx'),y=n('cy'),rx=n(tag==='circle'?'r':'rx'),ry=n(tag==='circle'?'r':'ry');
    return `M${x-rx} ${y}a${rx} ${ry} 0 1 0 ${2*rx} 0a${rx} ${ry} 0 1 0 ${-2*rx} 0Z`;
  }
  if (tag === 'rect') {
    const x=n('x'),y=n('y'),w=n('width'),h=n('height'),r=Math.min(n('rx'),w/2,h/2);
    if (!r) return `M${x} ${y}h${w}v${h}h${-w}Z`;
    return `M${x+r} ${y}h${w-2*r}a${r} ${r} 0 0 1 ${r} ${r}v${h-2*r}a${r} ${r} 0 0 1 ${-r} ${r}h${2*r-w}a${r} ${r} 0 0 1 ${-r} ${-r}v${2*r-h}a${r} ${r} 0 0 1 ${r} ${-r}Z`;
  }
  throw Error('Unsupported Lucide shape: '+tag);
}
const icons=[];
for (const file of (await readdir(base)).filter(n => n.endsWith('.svg')).sort()) {
  const svg = await readFile(new URL(file, base), 'utf8');
  const paths=[...svg.matchAll(/<(path|circle|rect|line|polyline|polygon|ellipse)\s+([^>]+?)\s*\/?\s*>/g)].map(([,tag,attrs])=>path(tag,Object.fromEntries([...attrs.matchAll(/([\w-]+)="([^"]*)"/g)].map(([,k,v])=>[k,v]))));
  icons.push([file.slice(0,-4),paths.join(' ')]);
}
const output=`// Generated by bun tools/build-icons.mjs from Lucide 1.72.0 (ISC).
// One path per icon avoids multiplying SVG branches for every layer row.
fn iconPath(name: string): string = ${icons.map(([name,d])=>`name == ${JSON.stringify(name)} ? ${JSON.stringify(d)} : `).join('')}""

component Icon
  props
    name: string
    size: number
    angle: number
  view
    svg width=size height=size rotate=angle viewBox="0 0 24 24" flex-shrink=0 aria-hidden=true pointer-events="none"
      path d=iconPath(name) fill="none" stroke="currentColor" stroke-width=1.75 stroke-linecap="round" stroke-linejoin="round"
`;
await writeFile(new URL('../studio/icons.contract', import.meta.url), output);
